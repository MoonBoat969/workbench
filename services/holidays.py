def ensure_holidays_loaded():
    """节假日内置数据同步进数据库（只插入不覆盖已有维护记录）。"""
    existing = {r["date"] for r in db.query("SELECT date FROM holiday")}
    rows = [(d, n, w) for d, (n, w) in HOLIDAYS.items() if d not in existing]
    if rows:
        db.execute_many(
            "INSERT OR IGNORE INTO holiday (date, name, is_work) VALUES (?, ?, ?)",
            rows,
        )
    return len(rows)


def is_holiday(date_str):
    """返回 (是否节假日, 是否调休上班, 名称)。"""
    row = db.query_one("SELECT * FROM holiday WHERE date=?", (date_str,))
    if row:
        return (row["is_work"] == 0), (row["is_work"] == 1), row["name"]
    return False, False, ""


def holidays_between(start_str, end_str):
    """一次查询区间内全部节假日，避免逐格查询（N+1）。

    返回 {date: (是否节假日, 是否调休上班, 名称)}。
    """
    rows = db.query("SELECT * FROM holiday WHERE date>=? AND date<=?",
                    (start_str, end_str))
    return {r["date"]: (r["is_work"] == 0, r["is_work"] == 1, r["name"])
            for r in rows}


def is_workday(date_str):
    """是否工作日：默认周一~周五为工作日，节假日休息、调休日上班。"""
    h, w, _ = is_holiday(date_str)
    if w:
        return True
    if h:
        return False
    d = datetime.strptime(date_str, "%Y-%m-%d")
    return d.weekday() < 5


def get_holidays(year=None):
    """查询节假日列表，可按年份过滤。"""
    if year:
        return db.query(
            "SELECT * FROM holiday WHERE date LIKE ? ORDER BY date",
            (f"{year}%",),
        )
    return db.query("SELECT * FROM holiday ORDER BY date")


def add_holiday(date_str, name, is_work=0):
    db.execute(
        "INSERT OR REPLACE INTO holiday (date, name, is_work) VALUES (?, ?, ?)",
        (date_str, name, int(is_work)),
    )


def remove_holiday(date_str):
    db.execute("DELETE FROM holiday WHERE date=?", (date_str,))


def next_date(d, step_days=1):
    return (datetime.strptime(d, "%Y-%m-%d") + timedelta(days=step_days)).strftime("%Y-%m-%d")


def holiday_json_path():
    return os.path.join(config.DATA_DIR, "holidays_extra.json")


def export_holidays(path):
    rows = get_holidays()
    with open(path, "w", encoding="utf-8") as f:
        json.dump(rows, f, ensure_ascii=False, indent=2)
    return len(rows)


def import_holidays(path):
    with open(path, "r", encoding="utf-8") as f:
        rows = json.load(f)
    n = 0
    for r in rows:
        add_holiday(r["date"], r.get("name", ""), r.get("is_work", 0))
        n += 1
    return n